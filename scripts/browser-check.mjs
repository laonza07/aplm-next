// Optional local QA: playwright-core is kept in ignored .qa/tools, not a site dependency.
import { chromium } from '../.qa/tools/package/index.mjs';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
await mkdir(new URL('../.qa/',import.meta.url),{recursive:true});
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const errors=[];
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
page.on('pageerror',error=>errors.push(error.message));
page.on('response',response=>{if(response.status()>=400&&response.url().startsWith('http://127.0.0.1:4177'))errors.push(`${response.status()} ${response.url()}`);});
await page.goto('http://127.0.0.1:4177',{waitUntil:'networkidle'});
await page.evaluate(()=>document.fonts.ready);
assert.equal(await page.locator('.directory-link').count(),12);
assert.ok(await page.locator('#result-count').innerText().then(text=>text.includes('191')));
await page.screenshot({path:'.qa/desktop.png',fullPage:true});
await page.getByRole('button',{name:'บริการนักศึกษา',exact:true}).click();
assert.equal(await page.locator('#menu-student').isVisible(),true);
await page.screenshot({path:'.qa/desktop-menu.png'});
await page.keyboard.press('Escape');
assert.equal(await page.locator('#menu-student').isVisible(),false);
await page.locator('#service-search').fill('คำร้องขอพักการเรียน');
assert.equal(await page.locator('.directory-link').count(),1);
assert.ok((await page.locator('.directory-link').getAttribute('href')).includes('.pdf'));
await page.locator('#clear-search').click();
await page.getByRole('button',{name:'คำร้องและแบบฟอร์ม',exact:true}).click();
assert.equal(await page.locator('.directory-link').count(),12);
assert.ok((await page.locator('#result-count').innerText()).includes('16'));
await page.getByRole('button',{name:'ทั้งหมด',exact:true}).click();
await page.locator('#service-search').fill('zzzz-no-match');
assert.equal(await page.locator('#empty-state').isVisible(),true);
await page.locator('#reset-search').click();
await page.locator('#load-more').click();
assert.equal(await page.locator('.directory-link').count(),24);
await page.getByRole('button',{name:'ทั้งหมด',exact:true}).click();
await page.locator('a.service[data-select="calendar"]').click();
assert.equal(await page.locator('.filter[data-category="calendar"]').getAttribute('aria-pressed'),'true');
await page.getByRole('button',{name:'ทั้งหมด',exact:true}).click();
const overflow=[];
for(const width of [1440,1024,900,768,600,390,360]){
  await page.setViewportSize({width,height:900});
  const dimensions=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth}));
  if(dimensions.scrollWidth>width) overflow.push(dimensions);
}
assert.deepEqual(overflow,[],'Page must not overflow horizontally');
await page.setViewportSize({width:390,height:844});
await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
await page.screenshot({path:'.qa/mobile.png',fullPage:true});
await page.locator('.nav-toggle').click();
await page.getByRole('button',{name:'บริการนักศึกษา',exact:true}).click();
assert.equal(await page.locator('#menu-student').isVisible(),true);
await page.screenshot({path:'.qa/mobile-menu.png'});
await page.locator('#menu-student [data-select="requests"]').click();
assert.equal(await page.locator('.nav-toggle').getAttribute('aria-expanded'),'false');
assert.equal(await page.locator('.filter[data-category="requests"]').getAttribute('aria-pressed'),'true');
await page.emulateMedia({reducedMotion:'reduce'});
await page.evaluate(()=>scrollTo({top:400,behavior:'instant'}));
await page.waitForTimeout(80);
assert.equal(await page.locator('.hero-art').evaluate(element=>getComputedStyle(element).transform),'none');
const assets=await page.locator('img').evaluateAll(images=>images.every(image=>image.complete&&image.naturalWidth>0));
assert.equal(assets,true,'All images must load');
assert.deepEqual(errors,[],'Browser errors');
const report={result:'PASS',viewports:[1440,1024,900,768,600,390,360],checks:['desktop/mobile menu','Escape/focus','search/clear/empty','category shortcuts','pagination','all 191 original links','admission href','no horizontal overflow','reduced motion','all images/fonts loaded','no runtime/HTTP errors'],screenshots:['desktop.png','desktop-menu.png','mobile.png','mobile-menu.png']};
await writeFile('.qa/report.json',JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
await browser.close();
